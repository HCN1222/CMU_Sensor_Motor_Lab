#!/usr/bin/env python3
"""Build the self-contained Uno sketch from the shared sources.

    python generate_sketches.py          # write hardware_controller/hardware_controller.ino
    python generate_sketches.py --check  # exit 1 if the .ino is out of date (used by tests)

Edit controller_core.h, hardware_config.h or arduino_adapter.inc -- never the .ino.
"""
import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent
SOURCES = ("controller_core.h", "hardware_config.h", "arduino_adapter.inc")
TARGET = ROOT / "hardware_controller" / "hardware_controller.ino"
HEADER = ("// GENERATED by firmware/generate_sketches.py from "
          + ", ".join(SOURCES) + ".\n// Do not edit this file; edit the sources and regenerate.\n")


def build():
    parts = [HEADER]
    for name in SOURCES:
        text = (ROOT / name).read_text(encoding="utf-8")
        # Local includes are satisfied by concatenation; the sketch folder holds only the .ino.
        lines = [line for line in text.splitlines() if line.strip() != '#include "controller_core.h"']
        parts.append(f"// ===== {name} =====\n" + "\n".join(lines) + "\n")
    return "\n".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="verify the generated sketch is current")
    args = parser.parse_args()
    content = build()
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current.replace("\r\n", "\n") != content:
            print(f"{TARGET} is out of date: run python firmware/generate_sketches.py", file=sys.stderr)
            return 1
        print(f"{TARGET.name} matches its sources")
        return 0
    TARGET.parent.mkdir(exist_ok=True)
    with TARGET.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(content)
    print(TARGET)
    return 0


if __name__ == "__main__":
    sys.exit(main())
